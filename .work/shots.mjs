import { chromium } from "../.work/testkit/node_modules/playwright/index.mjs";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
await p.goto("http://127.0.0.1:4180/proboy-md", { waitUntil: "networkidle" });
await p.waitForSelector("#pmd-title");
await p.screenshot({ path: ".work/pmd-hero.png" });
await p.locator("#commands").scrollIntoViewIfNeeded();
await p.waitForTimeout(300);
await p.screenshot({ path: ".work/pmd-cmds.png" });
await p.fill(".cmd-search input", "pair");
await p.waitForTimeout(250);
await p.screenshot({ path: ".work/pmd-search.png" });
await p.goto("http://127.0.0.1:4180/demos/luxecart-store", { waitUntil: "networkidle" });
await p.waitForSelector(".d-hero h1");
await p.screenshot({ path: ".work/demo-luxe.png" });
