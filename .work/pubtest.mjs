import { chromium } from "../.work/testkit/node_modules/playwright/index.mjs";
import assert from "node:assert/strict";
const base = process.env.QA_BASE;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
await p.goto(base + "/", { waitUntil: "domcontentloaded" });
await p.waitForSelector(".hero-portrait, .portrait-missing");
const img = await p.locator(".hero-portrait").count();
const picker = await p.locator('.portrait-choose').count();
const controls = await p.locator('.portrait-preview-controls').count();
const og = await p.locator('meta[property="og:image"]').getAttribute("content");
assert.equal(img, 1, "published portrait renders in hero");
const src = await p.locator(".hero-portrait").getAttribute("src");
assert(src.includes("hero.jpg"), `hero src = ${src}`);
assert.equal(picker, 0, "no Select portrait picker when a portrait file exists");
assert.equal(controls, 0, "no Change/Publish controls when a portrait file exists");
assert.equal(og, "https://proboy.vercel.app/images/hero.jpg", "og:image follows the published portrait");
const alt = await p.locator('meta[property="og:image:alt"]').getAttribute("content");
console.log("portrait alt in og:", alt);
console.log("PASS: published portrait → hero shows it, picker+publish hidden, og:image = portrait");
await b.close();
